-- Oracle Database schema for MediTrack portfolio project.
-- Use fictional/demo data only. Execute in a dedicated schema.
CREATE TABLE patients (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(80) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR2(10) NOT NULL CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    email VARCHAR2(254) NOT NULL UNIQUE,
    phone VARCHAR2(25),
    notes VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE appointments (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id NUMBER NOT NULL,
    provider_name VARCHAR2(100) NOT NULL,
    appointment_datetime TIMESTAMP NOT NULL,
    status VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL
        CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    reason VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id)
        REFERENCES patients(id)
);

CREATE INDEX idx_patients_name ON patients(full_name);
CREATE INDEX idx_appointments_datetime ON appointments(appointment_datetime);
CREATE INDEX idx_appointments_status ON appointments(status);
